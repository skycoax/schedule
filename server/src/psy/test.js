// ─── Проверка ответов ───

export class PsyError extends Error {}
const bad = (msg) => { throw new PsyError(msg); };

const choice = (v, n) => (Number.isInteger(v) && v >= 0 && v < n ? v : null);

/**
 * Ответы страницы → чистый объект или PsyError. clean — очистка текста (social/text.js cleanText).
 * @returns {{ fio, group, birth, family, upbringing, upbringingOther, living, livingOther, freeTime, interests,
 *   figure, lateral: { fingers, eye, arms, clap }, q: number[] }}
 */
export function validateAnswers(b, clean) {
  const line = (v, max, name, required = true) => {
    const s = clean(typeof v === 'string' ? v : '', { multiline: false });
    if (required && !s) bad(`Заполните поле «${name}»`);
    if (s.length > max) bad(`Поле «${name}» длиннее ${max} знаков`);
    return s;
  };
  const text = (v, max, name) => {
    const s = clean(typeof v === 'string' ? v : '', { multiline: true, maxLines: 10 });
    if (!s) bad(`Заполните поле «${name}»`);
    if (s.length > max) bad(`Поле «${name}» длиннее ${max} знаков`);
    return s;
  };

  const fio = line(b.fio, 100, 'Ф.И.О.');
  if (fio.split(' ').length < 2) bad('Укажите фамилию и имя полностью');
  const group = line(b.group, 40, 'Номер группы');
  const birth = typeof b.birth === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(b.birth) ? b.birth : bad('Укажите дату рождения');
  const d = new Date(birth + 'T00:00:00Z');
  const year = Number(birth.slice(0, 4));
  if (Number.isNaN(d.getTime()) || d.toISOString().slice(0, 10) !== birth || year < 1940 || year > new Date().getUTCFullYear() - 12) {
    bad('Проверьте дату рождения');
  }

  const family = choice(b.family, PERSONAL.family.length) ?? bad('Выберите семейное положение');
  // «Другое» — индекс -1 и свой текст (в форме у этих вопросов был вариант «Другое»).
  const other = (v, n, txt, name) => {
    if (v === -1) return { v: -1, other: line(txt, 100, name) };
    return { v: choice(v, n) ?? bad(`Ответьте на вопрос «${name}»`), other: '' };
  };
  const up = other(b.upbringing, PERSONAL.upbringing.length, b.upbringingOther, 'Семейная ситуация');
  const lv = other(b.living, PERSONAL.living.length, b.livingOther, 'Где Вы проживаете');
  const freeTime = text(b.freeTime, 500, 'Свободное время');
  const interests = text(b.interests, 500, 'Интересы');

  const figure = FIGURES.includes(b.figure) ? b.figure : bad('Выберите фигуру');
  const lat = b.lateral && typeof b.lateral === 'object' ? b.lateral : {};
  const lateral = {};
  for (const { key } of LATERAL) lateral[key] = lat[key] === 'L' || lat[key] === 'R' ? lat[key] : bad('Выполните все четыре пробы руками и глазом');

  const q = Array.isArray(b.q) && b.q.length === QUESTIONS.length ? b.q.map((v) => choice(v, 4)) : [];
  if (q.length !== QUESTIONS.length || q.some((v) => v === null)) bad('Ответьте на все вопросы');

  return {
    fio, group, birth, family, upbringing: up.v, upbringingOther: up.other, living: lv.v, livingOther: lv.other,
    freeTime, interests, figure, lateral, q,
  };
}


function lateralResult(lat) {
  const lead = { fingers: lat.fingers, eye: lat.eye === 'L' ? 'R' : 'L', arms: lat.arms, clap: lat.clap };
  const code = ['fingers', 'eye', 'arms', 'clap'].map((k) => (lead[k] === 'R' ? 'П' : 'Л')).join('');
  const rights = [...code].filter((c) => c === 'П').length;
  const style = rights >= 3
    ? { name: 'Рационал', text: 'Преобладают логика, последовательность и твёрдость.' }
    : rights === 2
      ? { name: 'Баланс', text: 'Логика и интуиция в равновесии — вы опираетесь на обе.' }
      : { name: 'Интуит', text: 'Преобладают образное мышление, чуткость и гибкость.' };
  return {
    code, style,
    signs: Object.keys(SIGN).map((k) => ({ key: k, title: SIGN[k].title, side: lead[k], text: SIGN[k][lead[k]] })),
  };
}

/** Итог теста по проверенным ответам (validateAnswers). Сохраняется в базе как есть. */
export function scoreAnswers(a) {
  const counts = [0, 0, 0, 0];
  a.q.forEach((v) => { counts[v] += 1; });
  const temps = TEMPS.map((id, i) => ({ id, name: TEMPERAMENT[id].name, color: TEMPERAMENT[id].color,
    count: counts[i], pct: Math.round((counts[i] / a.q.length) * 100) }));
  const sorted = [...temps].sort((x, y) => y.count - x.count || TEMPS.indexOf(x.id) - TEMPS.indexOf(y.id));
  const [top, second] = sorted;
  const lead = TEMPERAMENT[top.id];

  let headline;
  if (sorted[0].count - sorted[3].count <= 2) {
    headline = { kind: 'balanced', archetype: BALANCED.archetype, subtitle: 'Смешанный темперамент', text: BALANCED.text };
  } else if (second.count >= 3 && second.count >= top.count - 1) {
    const b = BLEND[[top.id, second.id].sort().join('+')];
    headline = { kind: 'blend', archetype: b.archetype, subtitle: `${lead.name} с чертами ${SECOND[second.id]}`, text: b.text };
  } else {
    headline = { kind: 'pure', archetype: lead.archetype, subtitle: lead.name, text: lead.text };
  }

  const axes = AXES.map((ax) => {
    let got = 0; let max = 0;
    for (const [qi, w] of ax.items) { got += w[a.q[qi]]; max += Math.max(...w); }
    return { key: ax.key, label: ax.label, hint: ax.hint, value: Math.round((got / max) * 100) };
  });
  const byValue = [...axes].sort((x, y) => y.value - x.value);

  return {
    v: 1,
    headline,
    temperament: { lead: top.id, second: second.id, list: temps, ...pick(lead, ['name', 'text', 'strengths', 'growth', 'tip', 'color']) },
    axes,
    top: byValue.slice(0, 2).map((x) => x.key),
    low: byValue[byValue.length - 1].key,
    figure: { id: a.figure, ...FIGURE[a.figure] },
    lateral: lateralResult(a.lateral),
  };
}

const pick = (o, keys) => Object.fromEntries(keys.map((k) => [k, o[k]]));

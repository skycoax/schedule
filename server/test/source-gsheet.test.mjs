// Разбор открытых Google-таблиц (server/src/source-gsheet.js): node --test server/test/source-gsheet.test.mjs
// Сетки — как в настоящих таблицах филиала КФУ (очное, очно-заочное, магистратура).
import test from 'node:test';
import assert from 'node:assert/strict';
import { isGroupHeader, normDay, parseCsv, parseGrid, timeOnly } from '../src/source-gsheet.js';

test('заголовок группы: код специальности, «N курс», «N к.»; шапка листа и даты — нет', () => {
  for (const s of ['1 курс Геология 05.03.01', '2 к. Лингвистика (оч-з.) 20-516', '5 к. Лечебное дело - 1.1 гр. 31.05.01',
    '1 курс Экономика 38.04.01 магистратура', '3 курс']) assert.ok(isGroupHeader(s), s);
  for (const s of ['', 'Пн', 'Расписание 1 семестра, 2 курса филиала КФУ в г. Джизаке. 2026_2027 уч. год.',
    'Расписание с 07.09.2026 года', '1-я пара 08:30 - 09:50', '1 курсовая работа', 'РЯ и КР 304 П ауд. Агишева З.Х. асс.'])
    assert.ok(!isGroupHeader(s), s);
});

test('день и время пары', () => {
  assert.equal(normDay('Пн'), 'Пн');
  assert.equal(normDay(' Понедельник '), 'Пн');
  assert.equal(normDay('Сб.'), 'Сб');
  assert.equal(normDay('Пара'), '');
  assert.equal(timeOnly('1-я пара          08:30 - 09:50'), '08:30 – 09:50');
  assert.equal(timeOnly('2-я пара          18:10 - 19-30'), '18:10 – 19:30');
  assert.equal(timeOnly('10:00 - 12:50'), '10:00 – 12:50');
  assert.equal(timeOnly('8.30–9.50'), '8:30 – 9:50');
  assert.equal(timeOnly('1-я пара'), '');
});

test('CSV: кавычки, "" внутри, перевод строки в ячейке, CRLF', () => {
  assert.deepEqual(parseCsv('"a","b ""c""","d\ne"\r\n"1",,"3"\n'), [['a', 'b "c"', 'd\ne'], ['1', '', '3']]);
});

const row = (...cells) => cells;

test('очно-заочное: «2 к. …», шесть пар, пустые ячейки — пустые пары', () => {
  const grid = [
    row('Расписание 1 семестра, 2 курса филиала КФУ в г. Джизаке. 2026_2027 уч. год. "Очно-заочная"', '', '', '', '', '', ''),
    row('2 к. Лингвистика (оч-з.) 20-516', '', '', '', '', '', ''),
    row('', '1-я пара 08:30 - 09:50', '2-я пара 10:00 - 11:20', '3-я пара 11:30 - 12:50', '4-я пара 13:40 - 15:00', '5-я пара 15:10 - 16:30', '6-я пара 16:40 - 18:00'),
    row('Пн', 'РЯ и КР   304 П ауд.   Агишева З.Х. асс.', '', '', '', '', ''),
    row('Вт', '', 'Экономика 304 П ауд. Абдурасулова Д.А. асс.', '', '', '', ''),
    row('2 к. Экономика (оч.-з.) 20-515', '', '', '', '', '', ''),
    row('', '1-я пара 08:30 - 09:50', '2-я пара 10:00 - 11:20', '3-я пара 11:30 - 12:50', '4-я пара 13:40 - 15:00', '5-я пара 15:10 - 16:30', '6-я пара 16:40 - 18:00'),
    row('Пн', '', '', '', '', '', 'Математика 305 П ауд. Мирзаев А.Н. асс.'),
  ];
  const { header, groups } = parseGrid(grid, '2 курс очно-заочное');
  assert.equal(header, '', 'шапка — как у Apps Script: только «Расписание с <дата> …»');
  assert.equal(parseGrid([row('Расписание с 07.09.2026 года, 1 семестра'), ...grid.slice(1)], 'x').header, 'Расписание с 07.09.2026 года, 1 семестра');
  assert.equal(groups.length, 2);
  const [a, b] = groups;
  assert.deepEqual({ key: a.key, sheet: a.sheet, course: a.course, name: a.name, link: a.link }, {
    key: '2 курс очно-заочное :: 2 к. Лингвистика (оч-з.) 20-516', sheet: '2 курс очно-заочное', course: '',
    name: '2 к. Лингвистика (оч-з.) 20-516', link: '',
  });
  assert.equal(a.times.length, 6);
  assert.deepEqual(a.days, [
    { day: 'Пн', pairs: ['РЯ и КР 304 П ауд. Агишева З.Х. асс.', '', '', '', '', ''] },
    { day: 'Вт', pairs: ['', 'Экономика 304 П ауд. Абдурасулова Д.А. асс.', '', '', '', ''] },
  ]);
  assert.equal(b.days[0].pairs[5], 'Математика 305 П ауд. Мирзаев А.Н. асс.');
});

test('магистратура: столбцы — по ширине листа, одни на все группы; пустое время — из того же столбца у соседей; «19-30»', () => {
  const grid = [
    row('Расписание 1 семестра, 1 курса филиала КФУ в г. Джизаке. 2026_2027 уч. год. (магистратура)', '', '', '', ''),
    row('1 курс Экономика 38.04.01 магистратура', '', '', '', 'https://telemost.yandex.ru/j/69727441704011'),
    row('', '', '1-я пара          16:40 - 18:00', '2-я пара          18:10 - 19-30', ' 3-я пара          19:40 - 21:00'),
    row('Пн', '', 'Консультации', 'Консультации', ''),
    row('Чт', '', '', '', ''),
    row('1 курс Лингвистика 45.04.02 магистратура', '', '', '', 'https://telemost.yandex.ru/j/37748502091555'),
    row('', '10:00 - 12:50', '1-я пара 16:40 - 18:00', '2-я пара 18:10 - 19-30', '3-я пара 19:40 - 21:00'),
    row('Ср', 'Педагогическая практика', 'История и метод. науки', '', ''),
  ];
  const [eco, lin] = parseGrid(grid, 'Магистратура').groups;
  assert.equal(eco.link, 'https://telemost.yandex.ru/j/69727441704011');
  assert.equal(eco.name, '1 курс Экономика 38.04.01 магистратура');
  assert.equal(eco.course, '1');
  // Номер пары не зависит от того, заполнен ли у группы столбец B: вуз впишет туда пару — остальные не «съедут».
  assert.deepEqual(eco.times, ['10:00 – 12:50', '16:40 – 18:00', '18:10 – 19:30', '19:40 – 21:00']);
  assert.deepEqual(eco.days, [{ day: 'Пн', pairs: ['', 'Консультации', 'Консультации', ''] }, { day: 'Чт', pairs: ['', '', '', ''] }]);
  assert.deepEqual(lin.times, ['10:00 – 12:50', '16:40 – 18:00', '18:10 – 19:30', '19:40 – 21:00']);
  assert.deepEqual(lin.days[0], { day: 'Ср', pairs: ['Педагогическая практика', 'История и метод. науки', '', ''] });
});

test('как у Apps Script (основная таблица): ровно столбцы B–G, время не дополняется, лишние столбцы справа не читаются', () => {
  const grid = [
    row('1 курс Геология 05.03.01', '', '', '', '', '', '', 'заметка'),
    row('', '1-я пара 08:30 - 09:50', '', '', '', '', '', ''),
    row('Пн', 'Геодезия', '', '', '', '', '', 'не пара'),
  ];
  const [g] = parseGrid(grid, '1 курс очное', { apps: true }).groups;
  assert.equal(g.times.length, 6);
  assert.deepEqual(g.times, ['08:30 – 09:50', '', '', '', '', '']);
  assert.deepEqual(g.days[0].pairs, ['Геодезия', '', '', '', '', '']);
  assert.deepEqual(Object.keys(g), ['key', 'sheet', 'course', 'name', 'link', 'times', 'days'], 'поля и порядок — как у Apps Script');
  assert.equal(parseGrid(grid, 'x', { sub: 'Лист2' }).groups[0].sub, 'Лист2');
});

test('очное: ссылка в строке группы не попадает в название; строки между днями пропускаются', () => {
  const grid = [
    row('1 курс Геология 05.03.01', '', '', '', '', 'https://telemost.yandex.ru/j/88007362143023', ''),
    row('', '1-я пара 08:30 - 09:50', '2-я пара 10:00 - 11:20', '3-я пара 11:30 - 12:50', '4-я пара 13:40 - 15:00', '5-я пара 15:10 - 16:30', '6-я пара 16:40 - 18:00'),
    row('Пн', '', 'Геодезия', '', '', '', ''),
    row('', 'примечание', '', '', '', '', ''),
    row('Вт', 'Общая геология', '', '', '', '', ''),
  ];
  const [g] = parseGrid(grid, '1 курс очное').groups;
  assert.equal(g.key, '1 курс очное :: 1 курс Геология 05.03.01');
  assert.equal(g.link, 'https://telemost.yandex.ru/j/88007362143023');
  assert.deepEqual(g.days.map((d) => d.day), ['Пн', 'Вт']);
  assert.equal(g.times.length, 6);
});
